-- Run only against approved Opsi application database, never OpenMetadata internal DB.
CREATE SCHEMA IF NOT EXISTS opsi_ingest;
CREATE SCHEMA IF NOT EXISTS opsi_chat;
CREATE SCHEMA IF NOT EXISTS opsi_knowledge;
CREATE TABLE IF NOT EXISTS opsi_ingest.incident_events (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 tenant_id text NOT NULL,
 source text NOT NULL,
 event_uid text NOT NULL,
 event_time timestamptz NOT NULL,
 ingested_at timestamptz NOT NULL DEFAULT now(),
 severity text,
 service_id text,
 message text,
 raw jsonb NOT NULL,
 UNIQUE(tenant_id,source,event_uid)
);
CREATE INDEX IF NOT EXISTS ix_opsi_events_tenant_time ON opsi_ingest.incident_events(tenant_id,event_time DESC);
CREATE INDEX IF NOT EXISTS ix_opsi_events_service_time ON opsi_ingest.incident_events(tenant_id,service_id,event_time DESC);
CREATE TABLE IF NOT EXISTS opsi_chat.folders (
 id uuid PRIMARY KEY, tenant_id text NOT NULL, owner_id text NOT NULL, name text NOT NULL,
 parent_id uuid REFERENCES opsi_chat.folders(id)
);
CREATE TABLE IF NOT EXISTS opsi_chat.threads (
 id uuid PRIMARY KEY,tenant_id text NOT NULL,owner_id text NOT NULL,
 folder_id uuid REFERENCES opsi_chat.folders(id), title text NOT NULL,
 linked_incident_id text, updated_at timestamptz NOT NULL DEFAULT now(), archived_at timestamptz
);
CREATE TABLE IF NOT EXISTS opsi_chat.messages (
 id uuid PRIMARY KEY,thread_id uuid NOT NULL REFERENCES opsi_chat.threads(id),
 role text NOT NULL,content_json jsonb NOT NULL,created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS opsi_chat.tags (
 id uuid PRIMARY KEY,tenant_id text NOT NULL,name text NOT NULL,
 UNIQUE(tenant_id,name)
);
CREATE TABLE IF NOT EXISTS opsi_chat.thread_tags (
 thread_id uuid NOT NULL REFERENCES opsi_chat.threads(id), tag_id uuid NOT NULL REFERENCES opsi_chat.tags(id),
 PRIMARY KEY(thread_id,tag_id)
);
CREATE TABLE IF NOT EXISTS opsi_chat.attachments (
 id uuid PRIMARY KEY,message_id uuid REFERENCES opsi_chat.messages(id),
 tenant_id text NOT NULL,s3_key text NOT NULL,mime_type text NOT NULL,
 sha256 text NOT NULL,scan_status text NOT NULL DEFAULT 'pending'
);
CREATE TABLE IF NOT EXISTS opsi_knowledge.entities (
 id uuid PRIMARY KEY,tenant_id text NOT NULL,kind text NOT NULL,name text NOT NULL,
 external_catalog_id text,attributes jsonb NOT NULL DEFAULT '{}'
);
CREATE TABLE IF NOT EXISTS opsi_knowledge.edges (
 id uuid PRIMARY KEY,tenant_id text NOT NULL,
 src_id uuid NOT NULL REFERENCES opsi_knowledge.entities(id),
 dst_id uuid NOT NULL REFERENCES opsi_knowledge.entities(id),
 relation_type text NOT NULL,valid_from timestamptz,valid_to timestamptz,
 evidence_ref text,confidence numeric,attributes jsonb NOT NULL DEFAULT '{}'
);
CREATE INDEX IF NOT EXISTS ix_ontology_edges_src ON opsi_knowledge.edges(tenant_id,src_id);
