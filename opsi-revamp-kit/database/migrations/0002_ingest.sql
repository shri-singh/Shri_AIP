-- 0002 - collector state (PostgreSQL backend) + curated operational subset.
-- Sizing: curated tables grow with *signatures and problems*, not log volume.
-- Expect O(10^4-10^5) rows/day per source. Retention job: see docs/runbooks.md.
-- Do NOT load raw logs here (the starter's opsi_ingest.incident_events.raw jsonb
-- pattern is intentionally not continued; raw data lives in S3 bronze).

SET ROLE opsi_owner;

-- ---------------------------------------------------------------- collector state
CREATE TABLE IF NOT EXISTS opsi_ingest.watermarks (
    source          text NOT NULL,
    dataset         text NOT NULL,
    committed_until timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL,
    PRIMARY KEY (source, dataset)
);

CREATE TABLE IF NOT EXISTS opsi_ingest.window_ledger (
    source            text NOT NULL,
    dataset           text NOT NULL,
    window_start      timestamptz NOT NULL,
    window_end        timestamptz NOT NULL,
    status            text NOT NULL CHECK (status IN ('running', 'bronze_committed', 'failed', 'skipped')),
    run_id            text,
    attempts          integer NOT NULL DEFAULT 0,
    scans             integer NOT NULL DEFAULT 0,
    record_count      integer NOT NULL DEFAULT 0,
    quarantined_count integer NOT NULL DEFAULT 0,
    manifest_key      text,
    last_error        text,
    last_scan_at      timestamptz,
    updated_at        timestamptz NOT NULL,
    PRIMARY KEY (source, dataset, window_start),
    CHECK (window_start < window_end)
);
CREATE INDEX IF NOT EXISTS ix_window_ledger_status ON opsi_ingest.window_ledger (status, window_start)
    WHERE status IN ('failed', 'running');

CREATE TABLE IF NOT EXISTS opsi_ingest.outbox (
    id              bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source          text NOT NULL,
    dataset         text NOT NULL,
    window_start    timestamptz NOT NULL,
    window_end      timestamptz NOT NULL,
    run_id          text NOT NULL,
    manifest_key    text NOT NULL,
    status          text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending', 'done', 'dead')),
    attempts        integer NOT NULL DEFAULT 0,
    next_attempt_at timestamptz NOT NULL,
    last_error      text,
    created_at      timestamptz NOT NULL,
    updated_at      timestamptz NOT NULL,
    UNIQUE (source, dataset, window_start, run_id)
);
CREATE INDEX IF NOT EXISTS ix_outbox_pending ON opsi_ingest.outbox (status, next_attempt_at);

CREATE TABLE IF NOT EXISTS opsi_ingest.runs (
    run_id      text PRIMARY KEY,
    source      text NOT NULL,
    stage       text NOT NULL,
    started_at  timestamptz NOT NULL,
    finished_at timestamptz,
    status      text NOT NULL,
    windows     integer NOT NULL DEFAULT 0,
    records     integer NOT NULL DEFAULT 0,
    detail      text
);

CREATE TABLE IF NOT EXISTS opsi_ingest.operator_actions (
    id           bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    at           timestamptz NOT NULL,
    actor        text NOT NULL,
    action       text NOT NULL,
    source       text NOT NULL,
    dataset      text NOT NULL,
    window_start timestamptz,
    reason       text NOT NULL
);

-- ---------------------------------------------------------------- curated subset
CREATE TABLE IF NOT EXISTS opsi_ingest.window_index_state (
    tenant_id    text NOT NULL,
    source       text NOT NULL,
    dataset      text NOT NULL,
    window_start timestamptz NOT NULL,
    run_id       text NOT NULL,          -- newest applied run; older runs are ignored
    applied_at   timestamptz NOT NULL,
    PRIMARY KEY (tenant_id, source, dataset, window_start)
);

CREATE TABLE IF NOT EXISTS opsi_ingest.problems (
    tenant_id            text NOT NULL,
    problem_id           text NOT NULL,          -- Dynatrace problemId
    display_id           text,                   -- e.g. P-24101
    title                text NOT NULL,
    status               text,                   -- OPEN | CLOSED
    severity_level       text,
    impact_level         text,
    start_time           timestamptz NOT NULL,
    end_time             timestamptz,
    root_cause_entity_id text,
    affected_entity_ids  jsonb NOT NULL DEFAULT '[]'::jsonb,
    management_zones     jsonb NOT NULL DEFAULT '[]'::jsonb,
    record_version       text NOT NULL,
    evidence_ref         text NOT NULL,          -- dynatrace-problem://<id>
    last_observed_at     timestamptz NOT NULL,
    search_tsv           tsvector GENERATED ALWAYS AS
                         (to_tsvector('simple', coalesce(display_id, '') || ' ' || coalesce(title, ''))) STORED,
    PRIMARY KEY (tenant_id, problem_id)
);
CREATE INDEX IF NOT EXISTS ix_problems_time ON opsi_ingest.problems (tenant_id, start_time DESC);
CREATE INDEX IF NOT EXISTS ix_problems_root ON opsi_ingest.problems (tenant_id, root_cause_entity_id);
CREATE INDEX IF NOT EXISTS ix_problems_entities ON opsi_ingest.problems USING gin (affected_entity_ids jsonb_path_ops);
CREATE INDEX IF NOT EXISTS ix_problems_tsv ON opsi_ingest.problems USING gin (search_tsv);

CREATE TABLE IF NOT EXISTS opsi_ingest.error_signature_windows (
    tenant_id      text NOT NULL,
    source         text NOT NULL,
    window_start   timestamptz NOT NULL,
    window_end     timestamptz NOT NULL,
    service_id     text NOT NULL DEFAULT '',
    fingerprint    text NOT NULL,
    severity       text NOT NULL,
    event_count    integer NOT NULL CHECK (event_count > 0),
    first_seen     timestamptz NOT NULL,
    last_seen      timestamptz NOT NULL,
    sample_message text,                         -- redacted, <= 500 chars
    sample_ref     text NOT NULL,                -- citation pointer (elastic://..., grail://...)
    run_id         text NOT NULL,
    search_tsv     tsvector GENERATED ALWAYS AS (to_tsvector('simple', coalesce(sample_message, ''))) STORED,
    PRIMARY KEY (tenant_id, source, window_start, service_id, fingerprint)
);
CREATE INDEX IF NOT EXISTS ix_sigwin_service_time ON opsi_ingest.error_signature_windows (tenant_id, service_id, window_start DESC);
CREATE INDEX IF NOT EXISTS ix_sigwin_fp ON opsi_ingest.error_signature_windows (tenant_id, fingerprint, window_start DESC);
CREATE INDEX IF NOT EXISTS ix_sigwin_brin ON opsi_ingest.error_signature_windows USING brin (window_start);
CREATE INDEX IF NOT EXISTS ix_sigwin_tsv ON opsi_ingest.error_signature_windows USING gin (search_tsv);

CREATE TABLE IF NOT EXISTS opsi_ingest.evidence_samples (
    tenant_id       text NOT NULL,
    event_uid       text NOT NULL,
    source          text NOT NULL,
    window_start    timestamptz NOT NULL,
    service_id      text NOT NULL DEFAULT '',
    fingerprint     text NOT NULL,
    severity        text NOT NULL,
    event_time      timestamptz NOT NULL,
    message_excerpt text,                        -- redacted, <= 1000 chars
    source_ref      text NOT NULL,
    trace_id        text,
    run_id          text NOT NULL,
    PRIMARY KEY (tenant_id, event_uid)
);
CREATE INDEX IF NOT EXISTS ix_samples_sig ON opsi_ingest.evidence_samples (tenant_id, fingerprint, event_time DESC);
CREATE INDEX IF NOT EXISTS ix_samples_window ON opsi_ingest.evidence_samples (tenant_id, source, window_start);

-- Hourly convenience view (replace-semantics per window make this safe to SUM).
-- Views execute with the owner's rights; RLS still filters because 0005 sets
-- FORCE ROW LEVEL SECURITY on the base table and policies read the *session* setting.
CREATE OR REPLACE VIEW opsi_ingest.error_signatures_hourly WITH (security_barrier) AS
SELECT tenant_id, source, service_id, fingerprint, date_trunc('hour', window_start) AS hour,
       CASE WHEN bool_or(severity = 'CRITICAL') THEN 'CRITICAL' ELSE 'ERROR' END AS severity,
       sum(event_count)::bigint AS event_count,
       min(first_seen) AS first_seen, max(last_seen) AS last_seen
FROM opsi_ingest.error_signature_windows
GROUP BY 1, 2, 3, 4, 5;

